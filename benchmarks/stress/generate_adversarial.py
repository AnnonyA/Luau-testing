"""Generate reproducible stateful mixed-feature programs, without external inputs.

Each program combines all templates in a different seeded order and additionally
revisits a subset, so earlier mutations affect later operations. The generator
is intentionally deterministic; the resulting .luau files are checked in.
"""
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parent
CASE_COUNT = 32
SEEDS = range(CASE_COUNT)

HEAD = '''-- Generated by generate_adversarial.py; state flows across all blocks.
return function(seed)
    local total = seed + 7
    local events = {}
    local function mark(tag, value)
        events[#events + 1] = tag .. ":" .. tostring(value)
        return value
    end
    local cells = {seed + 2, seed - 3, seed * 2, 5}
    local state = {counter = seed, toggle = false}
    local function mutate(index, amount)
        mark("mutate", index)
        cells[index] += amount
        state.counter += 1
        return cells[index], state.counter
    end
    local function results(value)
        mark("results", value)
        return value, nil, value + 1
    end
'''
TAIL = '''    for index = 1, 4 do
        mark("final" .. index, cells[index])
        total += cells[index]
    end
    mark("counter", state.counter)
    return total, table.concat(events, ","), nil, #events
end
'''

# Blocks must be deterministic, bounded, independently scoped, and must not
# inspect environment-specific error text, object addresses, or table order.
BLOCKS = [
'''    do -- captured loop cells and shared upvalues
        local functions = {}
        for j = 1, 3 do
            local captured = cells[j] + @K@
            functions[j] = function(delta)
                captured += delta
                local value, count = mutate(j, delta)
                return captured, value, count
            end
        end
        local a, b, c = functions[2](1)
        local d, e = functions[2](-1)
        total += a + b + c + d - e
        mark("closure@I@", total)
    end
''',
'''    do -- custom stateful generic iterator, continue and break
        local function iter(_, previous)
            local n = previous + 1
            mark("next@I@", n)
            if n > 5 then return nil end
            return n, cells[(n - 1) % 4 + 1]
        end
        for key, value in iter, nil, 0 do
            if (key + seed + @K@) % 4 == 0 then continue end
            total += value * key
            if key == 4 and state.counter % 2 == 0 then break end
        end
        cells[4] += total % 7
    end
''',
'''    do -- coroutine resume/yield with nil-bearing result lists
        local thread = coroutine.create(function(initial)
            local sent = coroutine.yield(initial + cells[1], nil, @K@)
            cells[2] += sent
            return results(sent + @K@)
        end)
        local ok1, a, b, c = coroutine.resume(thread, seed)
        local ok2, d, e, f = coroutine.resume(thread, @K@)
        mark("co@I@", tostring(ok1) .. ":" .. tostring(ok2) .. ":" .. tostring(b) .. ":" .. tostring(e))
        if ok1 and ok2 and b == nil and e == nil then total += a + c + d + f end
    end
''',
'''    do -- metamethod ordering and compound assignment on a proxy
        local backing = {value = cells[1]}
        local proxy = setmetatable({}, {
            __index = function(_, key) mark("read@I@", key); return backing[key] end,
            __newindex = function(_, key, value) mark("write@I@", key); backing[key] = value end,
        })
        local function key() mark("key@I@", @K@); return "value" end
        local function rhs() mark("rhs@I@", @K@); return cells[2] end
        proxy[key()] += rhs()
        cells[1] = proxy.value
        total += backing.value
    end
''',
'''    do -- table aliasing and multiple-assignment evaluation order
        local alias = cells
        local index = (state.counter + @K@) % 4 + 1
        local function ix() mark("idx@I@", index); return index end
        local function side() mark("side@I@", cells[2]); return cells[2] + @K@ end
        alias[ix()], index, cells[2] = side(), index % 4 + 1, cells[index]
        total += alias[index] + cells[2]
    end
''',
'''    do -- nested varargs and open return tails
        local function wrap(...)
            local args = table.pack(...)
            mark("arity@I@", args.n)
            return args.n, table.unpack(args, 1, args.n)
        end
        local n, a, b, c = wrap(results(cells[3] + @K@))
        if n == 3 and b == nil then
            cells[3] = a - c
            total += n + a + c
        else total -= n end
    end
''',
'''    do -- recursive calls and post-call upvalue reads
        local x = @K@
        local function walk(n)
            x += n
            if n == 0 then return x, nil end
            local left, absent = walk(n - 1)
            if absent == nil then x += 1 end
            return left + x, absent
        end
        local value, absent = walk(3)
        if absent == nil then total += value + x end
        cells[4] += x % 5
        mark("rec@I@", x)
    end
''',
'''    do -- short circuit operands and truthiness of zero
        local function choose(tag, value)
            mark(tag, value)
            state.counter += 1
            return value
        end
        local value = (seed % 2 == 0 and choose("yes@I@", 0)) or choose("no@I@", cells[4])
        local other = (state.toggle and choose("left@I@", false)) or choose("right@I@", @K@)
        state.toggle = not state.toggle
        total += value + other
    end
''',
'''    do -- arithmetic and comparison metamethods with observable callbacks
        local meta = {}
        meta.__add = function(a, b) mark("add@I@", a.value); return setmetatable({value = a.value + b.value}, meta) end
        meta.__lt = function(a, b) mark("lt@I@", b.value); return a.value < b.value end
        meta.__call = function(a, b) mark("call@I@", b); return a.value + b end
        local a = setmetatable({value = cells[1]}, meta)
        local b = setmetatable({value = @K@}, meta)
        local c = a + b
        if c < a then total -= c(@K@) else total += c(@K@) end
    end
''',
'''    do -- protected error through a captured mutation
        local function mayfail(v)
            cells[2] += v
            mark("try@I@", v)
            if (v + seed) % 3 == 0 then error("controlled") end
            return cells[2], nil, v
        end
        local ok, a, b, c = pcall(mayfail, @K@)
        mark("ok@I@", ok)
        if ok and b == nil then total += a + c else total -= cells[2] end
    end
''',
'''    do -- nested loop exits and values surviving each join
        local outer = 0
        while outer < 4 do
            outer += 1
            local j = 0
            repeat
                j += 1
                if (j + outer + seed + @K@) % 3 == 0 then continue end
                cells[3] += j - outer
                if (cells[3] + @K@) % 5 == 0 then break end
                total += cells[3]
            until j == 3
            if total % 19 == 0 then break end
        end
        mark("loop@I@", outer)
    end
''',
'''    do -- NaN, signed infinity, bitwise arithmetic and branch negation
        local zero = seed - seed
        local nan = zero / zero
        local bits = bit32.bxor(bit32.band(cells[4], 255), @K@)
        if not (nan < bits) and nan ~= nan and not (bits < -1) then
            total += bits
        else total -= bits end
        cells[4] = bits % 17
        mark("bits@I@", bits)
    end
''',
'''    do -- nested closures escaping lexical scope and mutating an alias
        local original = cells
        local function factory(n)
            local shared = n
            local function read() return shared, original[1] end
            local function write(v) shared += v; original[1] -= v; return read() end
            return read, write
        end
        local read, write = factory(@K@)
        local a, b = write(seed % 3)
        local c, d = read()
        total += a + b + c + d
    end
''',
'''    do -- open table constructor, keyed tail, and truncation contexts
        local list = {mark("first@I@", @K@), results(cells[2])}
        local one = (results(cells[1]))
        if list[3] == nil then total += list[1] + list[2] + list[4] + one end
        cells[2] = list[4] - one
    end
''',
'''    do -- variable reassignment of closures sharing one local
        local x = cells[1]
        local function nextvalue() x += @K@; return x end
        local old = nextvalue
        nextvalue = function() x -= 1; return x end
        local a, b, c = old(), nextvalue(), old()
        cells[1] = x
        total += a - b + c
        mark("replace@I@", x)
    end
''',
'''    do -- duplicate lvalues and RHS calls
        local a = (state.counter + @K@) % 4 + 1
        local function v(n) mark("v@I@", n); return cells[a] + n end
        cells[a], cells[a] = v(1), v(2)
        total += cells[a]
        local x, y = cells[1], cells[2]
        x, y = y, x
        cells[1], cells[2] = x, y
    end
''',
]


def make_case(case_id):
    rng = random.Random(48911 + case_id * 104729)
    # Every source contains all 16 interaction types, with four revisits in a
    # different position. This changes dependencies as well as constants.
    order = list(range(len(BLOCKS))) + rng.sample(range(len(BLOCKS)), 4)
    rng.shuffle(order)
    blocks = []
    for position, block_id in enumerate(order):
        constant = rng.randint(1, 13)
        blocks.append(BLOCKS[block_id].replace('@I@', str(position)).replace('@K@', str(constant)))
    return HEAD + ''.join(blocks) + TAIL


def case_names():
    return tuple(f'adversarial_{i:02}' for i in SEEDS)


if __name__ == '__main__':
    for i, name in zip(SEEDS, case_names()):
        (ROOT / f'{name}.luau').write_text(make_case(i), encoding='utf-8', newline='\n')
